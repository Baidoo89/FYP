async function ensureBlobTable(client) {
  await client.$executeRawUnsafe(`
    CREATE TABLE IF NOT EXISTS "document_file_blobs" (
      "documentId" INTEGER PRIMARY KEY REFERENCES "documents"("id") ON DELETE CASCADE,
      "fileName" TEXT NOT NULL,
      "mimeType" TEXT NOT NULL,
      "size" INTEGER NOT NULL,
      "data" BYTEA NOT NULL,
      "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
      "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  `);
}

async function saveBlob(client, documentId, fileName, buffer) {
  await client.$executeRawUnsafe(
    `INSERT INTO "document_file_blobs" ("documentId", "fileName", "mimeType", "size", "data")
     VALUES ($1, $2, 'application/pdf', $3, $4)
     ON CONFLICT ("documentId") DO UPDATE SET
       "fileName" = EXCLUDED."fileName", "mimeType" = EXCLUDED."mimeType",
       "size" = EXCLUDED."size", "data" = EXCLUDED."data", "updatedAt" = CURRENT_TIMESTAMP`,
    documentId, fileName, buffer.length, buffer
  );
}

async function requireUsers(client) {
  const emails = Object.values(ROLE_EMAILS);
  const users = await client.user.findMany({ where: { email: { in: emails } } });
  const byEmail = new Map(users.map((user) => [user.email, user]));
  const missing = emails.filter((email) => !byEmail.has(email));
  if (missing.length) {
    throw new Error(`Missing seeded role accounts: ${missing.join(', ')}. Run npm run db:seed first.`);
  }
  return Object.fromEntries(Object.entries(ROLE_EMAILS).map(([key, email]) => [key, byEmail.get(email)]));
}

async function createDocuments(client, requestId, lecturerId, hrId, prefix, period, verified) {
  for (const [category, title] of EVIDENCE) {
    const fileName = `${prefix}-${category.toLowerCase().replaceAll('_', '-')}.pdf`;
    const buffer = await createEvidencePdf({ category, title, period });
    const document = await client.document.create({
      data: {
        promotionRequestId: requestId,
        requestId,
        uploadedById: lecturerId,
        category,
        title,
        description: `Representative ${label(category)} evidence for the academic defence scenario.`,
        fileUrl: `/api/uploads/${encodeURIComponent(fileName)}`,
        fileName,
        fileType: 'application/pdf',
        mimeType: 'application/pdf',
        fileSize: buffer.length,
        status: verified ? 'VERIFIED' : 'PENDING',
        verificationStatus: verified ? 'VERIFIED' : 'PENDING',
        verifiedById: verified ? hrId : null,
        verificationComment: verified ? 'Evidence checked and verified for the representative completed application.' : null,
        verifiedAt: verified ? at('2025-07-09') : null,
      },
    });
    if (verified) {
      await client.verification.create({
        data: {
          documentId: document.id,
          verifierId: hrId,
          decision: 'VERIFIED',
          comment: 'Evidence checked and verified for the representative completed application.',
          createdAt: at('2025-07-09'),
        },
      });
    }
    await saveBlob(client, document.id, fileName, buffer);
  }
}

