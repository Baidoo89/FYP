async function check() {
  const lecturer = await prisma.user.findUnique({
    where: { email: DEFENCE_USER.email },
    include: {
      lecturerRequests: {
        include: { documents: true, statusHistory: true },
        orderBy: { createdAt: 'asc' },
      },
    },
  });
  if (!lecturer) throw new Error('Benjamin Baidoo defence account is missing. Run npm run defence:prepare.');
  if (lecturer.lecturerRequests.length !== 2) throw new Error('Expected exactly two Benjamin Baidoo defence applications.');
  const completed = lecturer.lecturerRequests.find((request) => request.status === 'COMPLETED');
  const active = lecturer.lecturerRequests.find((request) => request.status !== 'COMPLETED');
  if (!completed || completed.documents.length !== EVIDENCE.length || completed.totalScore !== 100) {
    throw new Error('Completed defence application is incomplete. Run npm run defence:prepare.');
  }
  if (!active || active.status !== 'DRAFT' || active.documents.length !== EVIDENCE.length) {
    throw new Error('Active defence application is not a six-document draft. Run npm run defence:prepare.');
  }
  const documents = [...completed.documents, ...active.documents];
  const placeholders = documents.map((_, index) => `$${index + 1}`).join(', ');
  const rows = await prisma.$queryRawUnsafe(
    `SELECT COUNT(*)::int AS count FROM "document_file_blobs" WHERE "documentId" IN (${placeholders})`,
    ...documents.map((document) => document.id)
  );
  if (rows[0]?.count !== EVIDENCE.length * 2) throw new Error('One or more defence PDF blobs are missing.');
  return { lecturer, completed, active, blobCount: rows[0].count };
}

