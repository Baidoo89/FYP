function at(isoDate) {
  return new Date(`${isoDate}T09:00:00.000Z`);
}

function label(value) {
  return String(value)
    .toLowerCase()
    .split('_')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ');
}

